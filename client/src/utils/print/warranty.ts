export const NO_WARRANTY = 'Без гарантии';

// Варианты из CloseRecordModal в родительном падеже — «в течение 1 месяца»
export const WARRANTY_GENITIVE: { [term: string]: string } = {
  '1 месяц': '1 месяца',
  '6 месяцев': '6 месяцев',
  '1 год': '1 года',
};

/**
 * Подставляет выбранный при закрытии сделки гарантийный срок вместо прочерка «____»
 * в тексте гарантийных обязательств. Работает и с дефолтным текстом, и с шаблоном
 * из настроек. Если срок не выбран (или печатается пустой акт) — прочерк остаётся.
 */
export function fillWarrantyTerm(text: string, warranty?: string): string {
  if (!warranty) return text;

  const noWarranty = warranty === NO_WARRANTY;
  const term = WARRANTY_GENITIVE[warranty] ?? warranty;

  // Сначала пробуем заменить фразу «в течение ____» целиком: это позволяет
  // корректно напечатать вариант «Без гарантии», убрав «в течение».
  const phrase = /в течение\s+_{3,}/i;
  if (phrase.test(text)) {
    return text.replace(phrase, noWarranty ? 'гарантия не предоставляется' : `в течение ${term}`);
  }

  return text.replace(/_{3,}/, noWarranty ? 'гарантия не предоставляется' : term);
}
